"""Generate the secrets the app needs and (optionally) write a local .env file.

    python -m scripts.gen_secrets                 # print to the terminal only
    python -m scripts.gen_secrets --write         # create .env (refuses to overwrite an existing file)
    python -m scripts.gen_secrets --write --env production --tenant acme-bank

Keep ENC_KEY: documents are encrypted with it and cannot be decrypted without it. Never commit .env (it is git-ignored)."""
import argparse
import os
import secrets
import sys
from pathlib import Path


def build(env: str, tenant: str) -> tuple[dict, str]:
    keys = {r: secrets.token_urlsafe(24) for r in ("admin", "analyst", "viewer")}
    values = {
        "ENV": env,
        "DATABASE_URL": "",
        "REDIS_URL": "",
        "API_KEYS": ",".join(f"{k}:{r}:{tenant}" for r, k in keys.items()),
        "ENC_KEY": secrets.token_hex(32),
        "DOCS_ENABLED": "true" if env != "production" else "false",
    }
    text = (
        "# Generated by scripts/gen_secrets.py - NEVER commit this file.\n"
        "# Fill DATABASE_URL (Neon) and REDIS_URL (Upstash). Leave both empty to run with SQLite + in-process Redis (dev only).\n"
        f"ENV={values['ENV']}\n"
        "# Neon:    postgresql://user:pass@ep-xxxx-pooler.region.aws.neon.tech/neondb?sslmode=require   (converted automatically)\n"
        "DATABASE_URL=\n"
        "# Upstash: rediss://default:<password>@<host>.upstash.io:6379\n"
        "REDIS_URL=\n"
        f"API_KEYS={values['API_KEYS']}\n"
        f"ENC_KEY={values['ENC_KEY']}\n"
        f"DOCS_ENABLED={values['DOCS_ENABLED']}\n"
    )
    return {"keys": keys, **values}, text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", nargs="?", const=".env", metavar="PATH")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--env", default="dev", choices=["dev", "production"])
    ap.add_argument("--tenant", default="acme-bank")
    a = ap.parse_args(argv)
    vals, text = build(a.env, a.tenant)
    if a.write:
        path = Path(a.write)
        if path.exists() and not a.force:
            print(f"{path} already exists - not overwriting (use --force to replace; you would lose the old ENC_KEY).", file=sys.stderr)
            return 1
        path.write_text(text, encoding="utf8")
        try:
            os.chmod(path, 0o600)
        except OSError:
            pass
        print(f"Wrote {path}. Now paste your Neon URL into DATABASE_URL and your Upstash URL into REDIS_URL.")
        print("Your API keys (use one in the UI header):")
        for role, k in vals["keys"].items():
            print(f"  {role:8s} {k}")
        return 0
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
